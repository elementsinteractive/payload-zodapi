import type { JSONSchema4 } from 'json-schema'
import type { BinScript, SanitizedConfig } from 'payload'

import fs from 'node:fs'
import { configToJSONSchema } from 'payload'
import { FetchingJSONSchemaStore, InputData, JSONSchemaInput, quicktype } from 'quicktype-core'

import type { SchemaPreProcessor } from '../types'

export const DEFAULT_SCHEMAS_PATH = 'src/payload-schemas.ts'

// Script must define a "script" function export that accepts the sanitized config
export const script: BinScript = async (config: SanitizedConfig) => {
  const schemasPath = config.custom.zodApiPluginOpts?.schemasPath || DEFAULT_SCHEMAS_PATH
  const schemaPreProcessors: SchemaPreProcessor[] =
    config.custom.zodApiPluginOpts?.schemaPreProcessors ?? []

  const jsonSchema = configToJSONSchema(config, config.db.defaultIDType)

  const schemasContent = await jsonSchemaToZodSchemas(jsonSchema, schemaPreProcessors)
  const headers = [
    '// biome-ignore-all format: generated file',
    '// biome-ignore-all lint: generated file',
    '/* tslint:disable */',
    '/* eslint-disable */',
    '/**\n* This file was automatically generated by payload-zodapi.\n* DO NOT MODIFY IT BY HAND. Instead, modify your source Payload config,\n* and re-run `payload generate:schemas` to regenerate this file.\n*/',
  ]

  // Inject extendZodWithOpenApi(z) right after the `import * as z from "zod"`
  // line so that all schemas created in this file support .openapi() for
  // $ref registration.  The call is idempotent and must happen before any
  // z.* schema constructors run.
  const extendSnippet = [
    'import { extendZodWithOpenApi } from "@asteasolutions/zod-to-openapi";',
    'extendZodWithOpenApi(z);',
  ].join('\n')
  const enhancedContent = schemasContent.replace(
    'import * as z from "zod";',
    `import * as z from "zod";\n${extendSnippet}`,
  )

  // nosemgrep: eslint.detect-non-literal-fs-filename / Path is provided as CLI argument by developer, not user input
  fs.writeFileSync(schemasPath, `${headers.join('\n')}\n${enhancedContent}`)
}

const jsonSchemaToZodSchemas = async (
  jsonSchema: JSONSchema4,
  preProcessors: SchemaPreProcessor[],
) => {
  const filteredSchema = preprocessJsonSchema(jsonSchema, preProcessors)

  const schemaInput = new JSONSchemaInput(new FetchingJSONSchemaStore())

  await schemaInput.addSource({
    name: 'Schema',
    schema: JSON.stringify(filteredSchema),
  })

  const inputData = new InputData()
  inputData.addInput(schemaInput)

  const { lines: output } = await quicktype({
    inputData,
    lang: 'typescript-zod',
  })

  return output.join('\n')
}

/**
 * Strips `collectionsJoins` from a Payload JSON schema.
 *
 * Payload generates a top-level `collectionsJoins` property that defines inline
 * objects with the same names as collections (e.g. "seasonCovers") but only
 * containing join metadata fields. This causes quicktype to pick up the
 * join-only version instead of the full collection definition.
 */
const stripCollectionsJoins = (jsonSchema: JSONSchema4): JSONSchema4 => {
  const { collectionsJoins: _collectionsJoins, ...properties } = (jsonSchema.properties ??
    {}) as Record<string, JSONSchema4>

  return {
    ...jsonSchema,
    properties,
    required: (jsonSchema.required as string[] | undefined)?.filter(
      (r) => r !== 'collectionsJoins',
    ),
  }
}

/**
 * Applies the built-in `collectionsJoins` stripping and any additional
 * user-provided pre-processors to a Payload JSON schema.
 */
const preprocessJsonSchema = (
  jsonSchema: JSONSchema4,
  preProcessors: SchemaPreProcessor[] = [],
): JSONSchema4 => {
  let schema = stripCollectionsJoins(jsonSchema)

  for (const preProcessor of preProcessors) {
    schema = preProcessor(schema)
  }

  return schema
}
